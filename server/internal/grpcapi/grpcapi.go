// ──────────────────────────────────────────────
//  Configuration
// ──────────────────────────────────────────────

// Config holds gRPC server configuration.
type Config struct {
	ListenAddr string // e.g. "10.13.37.1:50051"
	CertFile   string // Server certificate PEM
	KeyFile    string // Server private key PEM
	CAFile     string // CA certificate PEM (for verifying client certs)
}

// ──────────────────────────────────────────────
//  Server
// ──────────────────────────────────────────────

// Server implements the C2Service gRPC API.
type Server struct {
	cfg      Config
	sessions *session.Manager
	audit    *audit.Logger
	logger   *log.Logger
	grpcSrv  *grpc.Server
}

// New creates a new gRPC API server.
func New(cfg Config, sessions *session.Manager, auditLog *audit.Logger) *Server {
	return &Server{
		cfg:      cfg,
		sessions: sessions,
		audit:    auditLog,
		logger:   log.New(os.Stdout, "[grpc] ", log.LstdFlags|log.Lmsgprefix),
	}
}

// Start begins serving the gRPC API with mutual TLS. It blocks until
// Stop is called.
func (s *Server) Start() error {
	creds, err := s.buildCredentials()
	if err != nil {
		return fmt.Errorf("grpcapi: credentials: %w", err)
	}

	s.grpcSrv = grpc.NewServer(grpc.Creds(creds))

	// Register service implementation.
	RegisterC2ServiceServer(s.grpcSrv, s)

	ln, err := net.Listen("tcp", s.cfg.ListenAddr)
	if err != nil {
		return fmt.Errorf("grpcapi: bind %s: %w", s.cfg.ListenAddr, err)
	}

	s.logger.Printf("gRPC API listening on %s (mTLS)", s.cfg.ListenAddr)

	return s.grpcSrv.Serve(ln)
}

// Stop gracefully shuts down the gRPC server.
func (s *Server) Stop() {
	if s.grpcSrv != nil {
		s.grpcSrv.GracefulStop()
	}
}

// ──────────────────────────────────────────────
//  TLS credentials (mTLS)
// ──────────────────────────────────────────────

func (s *Server) buildCredentials() (credentials.TransportCredentials, error) {
	cert, err := tls.LoadX509KeyPair(s.cfg.CertFile, s.cfg.KeyFile)
	if err != nil {
		return nil, fmt.Errorf("load keypair: %w", err)
	}

	caPEM, err := os.ReadFile(s.cfg.CAFile)
	if err != nil {
		return nil, fmt.Errorf("read CA cert: %w", err)
	}

	pool := x509.NewCertPool()
	if !pool.AppendCertsFromPEM(caPEM) {
		return nil, fmt.Errorf("failed to parse CA certificate")
	}

	tlsCfg := &tls.Config{
		Certificates: []tls.Certificate{cert},
		ClientAuth:   tls.RequireAndVerifyClientCert,
		ClientCAs:    pool,
		MinVersion:   tls.VersionTLS13,
	}

	return credentials.NewTLS(tlsCfg), nil
}

