// ListSessions returns all tracked sessions.
func (s *Server) ListSessions(_ context.Context, _ *pb.ListSessionsRequest) (*pb.ListSessionsResponse, error) {
	sessions := s.sessions.All()

	resp := &pb.ListSessionsResponse{
		Sessions: make([]*pb.SessionInfo, 0, len(sessions)),
	}

	for _, sess := range sessions {
		resp.Sessions = append(resp.Sessions, sessionToProto(sess))
	}

	s.logger.Printf("ListSessions: returned %d sessions", len(resp.Sessions))
	return resp, nil
}

// GetSession returns detailed information about a single session.
func (s *Server) GetSession(_ context.Context, req *pb.GetSessionRequest) (*pb.SessionInfo, error) {
	if req.SessionId == "" {
		return nil, status.Error(codes.InvalidArgument, "session_id is required")
	}

	sess := s.sessions.Get(req.SessionId)
	if sess == nil {
		return nil, status.Errorf(codes.NotFound, "session %s not found", req.SessionId)
	}

	return sessionToProto(sess), nil
}

// QueueTask enqueues a task for delivery to an agent on its next beacon.
func (s *Server) QueueTask(ctx context.Context, req *pb.QueueTaskRequest) (*pb.QueueTaskResponse, error) {
	if req.SessionId == "" {
		return nil, status.Error(codes.InvalidArgument, "session_id is required")
	}

	sess := s.sessions.Get(req.SessionId)
	if sess == nil {
		return nil, status.Errorf(codes.NotFound, "session %s not found", req.SessionId)
	}

	if sess.GetState() != session.StateActive {
		return nil, status.Errorf(codes.FailedPrecondition,
			"session %s is not active (state=%s)", req.SessionId, sess.GetState())
	}

	// Map proto TaskType to internal TaskType.
	tt := protoTaskTypeToInternal(req.TaskType)

	operator := req.Operator
	if operator == "" {
		operator = operatorFromContext(ctx)
	}

	taskID := sess.TaskQueue.Enqueue(tt, req.TaskData, operator)

	s.logger.Printf("QueueTask: session=%s task=%s type=%s operator=%s",
		req.SessionId, taskID, tt, operator)

	if s.audit != nil {
		s.audit.TaskEvent(audit.EventTaskDispatched, req.SessionId, operator,
			tt.String(), taskID, fmt.Sprintf("queued (%d bytes payload)", len(req.TaskData)))
	}

	return &pb.QueueTaskResponse{
		TaskId: taskID,
		Queued: true,
	}, nil
}

// GetResults retrieves collected results for a given session.
func (s *Server) GetResults(_ context.Context, req *pb.GetResultsRequest) (*pb.GetResultsResponse, error) {
	if req.SessionId == "" {
		return nil, status.Error(codes.InvalidArgument, "session_id is required")
	}

	sess := s.sessions.Get(req.SessionId)
	if sess == nil {
		return nil, status.Errorf(codes.NotFound, "session %s not found", req.SessionId)
	}

	results := sess.GetResults()

	resp := &pb.GetResultsResponse{
		Results: make([]*pb.TaskResult, 0, len(results)),
	}

	for _, r := range results {
		resp.Results = append(resp.Results, &pb.TaskResult{
			TaskId:     r.TaskID,
			SessionId:  req.SessionId,
			ResultData: r.Data,
			ErrorMsg:   r.Error,
			ReceivedAt: r.ReceivedAt.Unix(),
		})
	}

	return resp, nil
}

// Shutdown sends a graceful shutdown command to a specific agent session.
func (s *Server) Shutdown(_ context.Context, req *pb.ShutdownRequest) (*pb.ShutdownResponse, error) {
	if req.SessionId == "" {
		return nil, status.Error(codes.InvalidArgument, "session_id is required")
	}

	sess := s.sessions.Get(req.SessionId)
	if sess == nil {
		return nil, status.Errorf(codes.NotFound, "session %s not found", req.SessionId)
	}

	sess.RequestShutdown()

	s.logger.Printf("Shutdown: session=%s operator=%s", req.SessionId, req.Operator)

	if s.audit != nil {
		s.audit.SessionEvent(audit.EventSessionShutdown, req.SessionId,
			sess.RemoteAddr, fmt.Sprintf("operator=%s", req.Operator))
	}

	return &pb.ShutdownResponse{Success: true}, nil
}

// BroadcastShutdown sends a shutdown command to ALL active sessions.
func (s *Server) BroadcastShutdown(_ context.Context, req *pb.BroadcastShutdownRequest) (*pb.BroadcastShutdownResponse, error) {
	count := s.sessions.ShutdownAll()

	s.logger.Printf("BroadcastShutdown: %d sessions notified, operator=%s",
		count, req.Operator)

	if s.audit != nil {
		s.audit.ServerEvent(audit.EventBroadcastShutdown,
			fmt.Sprintf("operator=%s sessions=%d", req.Operator, count))
	}

	return &pb.BroadcastShutdownResponse{
		SessionsNotified: uint32(count),
	}, nil
}

