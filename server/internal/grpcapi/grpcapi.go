// Package grpcapi implements the operator-facing gRPC API for the
// Team Server.
//
// This service allows operators to:
//   - List and inspect agent sessions
//   - Queue tasks for delivery on the next beacon
//   - Retrieve task results
//   - Shut down individual sessions or broadcast shutdown
//
// All RPCs are served over mutual TLS (mTLS) — the operator must
// present a valid client certificate signed by the lab CA.
//
// ACADEMIC/EDUCATIONAL USE ONLY.
package grpcapi

