// sessionToProto converts an internal Session to a proto SessionInfo.
func sessionToProto(sess *session.Session) *pb.SessionInfo {
	sessState := sess.GetState()

	var protoState pb.SessionState
	switch sessState {
	case session.StateRegistered:
		protoState = pb.SessionState_SESSION_STATE_REGISTERED
	case session.StateActive:
		protoState = pb.SessionState_SESSION_STATE_ACTIVE
	case session.StateShutdown:
		protoState = pb.SessionState_SESSION_STATE_SHUTDOWN
	default:
		protoState = pb.SessionState_SESSION_STATE_UNSPECIFIED
	}

	return &pb.SessionInfo{
		SessionId:      sess.ID,
		Hostname:       sess.Hostname,
		Os:             sess.OS,
		Arch:           sess.Arch,
		State:          protoState,
		RegisteredAt:   sess.RegisteredAt.Unix(),
		LastSeen:       sess.LastSeenTime().Unix(),
		BeaconInterval: sess.BeaconInterval,
		Jitter:         uint32(sess.Jitter),
		SeqNumber:      sess.LastSeqNumber,
		RemoteAddr:     sess.RemoteAddr,
	}
}

// protoTaskTypeToInternal maps proto TaskType to the internal taskqueue type.
func protoTaskTypeToInternal(pt pb.TaskType) taskqueue.TaskType {
	switch pt {
	case pb.TaskType_TASK_TYPE_EXEC:
		return taskqueue.TaskExec
	case pb.TaskType_TASK_TYPE_UPLOAD:
		return taskqueue.TaskUpload
	case pb.TaskType_TASK_TYPE_DOWNLOAD:
		return taskqueue.TaskDownload
	case pb.TaskType_TASK_TYPE_SYSINFO:
		return taskqueue.TaskSysinfo
	case pb.TaskType_TASK_TYPE_SLEEP:
		return taskqueue.TaskSleep
	case pb.TaskType_TASK_TYPE_EXIT:
		return taskqueue.TaskExit
	default:
		return taskqueue.TaskExec
	}
}

// operatorFromContext extracts the operator identity from the gRPC
// peer's TLS certificate CN. Returns "unknown" if unavailable.
func operatorFromContext(ctx context.Context) string {
	if ctx == nil {
		return "unknown"
	}
	p, ok := peer.FromContext(ctx)
	if !ok {
		return "unknown"
	}
	tlsInfo, ok := p.AuthInfo.(credentials.TLSInfo)
	if !ok {
		return "unknown"
	}
	if len(tlsInfo.State.PeerCertificates) == 0 {
		return "unknown"
	}
	return tlsInfo.State.PeerCertificates[0].Subject.CommonName
}
